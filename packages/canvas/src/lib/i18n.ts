export function createTranslator(locale: CanvasLocale = { lang: "zh-CN" }): Translate {
    const base = locale.lang === "en-US" ? enUS : zhCN;
    const table = { ...base, ...(locale.messages ?? {}) };
    const fallback = locale.lang === "en-US" ? enUS : zhCN;
    return (key, vars) => {
        const template = table[key] ?? fallback[key] ?? key;
        if (!vars) return template;
        return template.replace(/\{(\w+)\}/g, (_, name: string) => String(vars[name] ?? `{${name}}`));
    };
}
